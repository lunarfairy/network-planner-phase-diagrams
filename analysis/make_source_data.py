"""Assemble Source_Data.xlsx (one sheet per figure, plus Table 1) from the processed tables.

Usage: python analysis/make_source_data.py <processed_dir> <out.xlsx>
"""
import sys, os
import pandas as pd

P, OUT = sys.argv[1], sys.argv[2]
r = lambda f: pd.read_csv(os.path.join(P, f))
PH = r('phase_table_certified.csv')
KW_COLS = [c for c in ('pid', 'kappa', 'w', 'AB_phase', 'A_phase', 'B_phase', 'AB_s_star', 'AB_dE', 'AB_dE_se', 'AB_dC', 'AB_dC_se',
                       'AB_raw_cls', 'AB_phase_eps0.0025', 'AB_phase_eps0.01', 'uncertain') if c in PH.columns]
SHEETS = [
    ('Fig1_ab_main_plane', PH[PH.grid == 'kw'][KW_COLS]),
    ('Fig1_c_slice_w0', r('slice_w0.csv')),
    ('Fig1_d_tolerance', r('tolerance_transitions.csv')),
    ('Fig2_a_theory', r('theory_endgame.csv')),
    ('Fig2_bcd_branches', r('mechanism_branches.csv')),
    ('Fig3_game_plane', r('game_plane.csv')),
    ('Fig3_rules', r('game_plane_rules.csv')),
    ('Fig4_robustness', r('robustness_strips.csv')),
    ('Fig4_size_network', r('size_network_stats.csv')),
    ('Fig4_horizon', r('horizon_window.csv')),
    ('Fig5_a_estimates', r('estimates.csv')),
    ('Fig5_b_kslice', r('empirical_kslice.csv')),
    ('Fig5_c_decomposition', r('decomposition.csv')),
    ('Fig5_d_objectives', r('empirical_multiobjective.csv')),
    ('Fig5_e_prediction', r('oos_table.csv')),
    ('Table1_fits', r('fits.csv')),
    ('Table1_tests', r('tests.csv')),
    ('SuppFig1_first_order', r('theory_all_rounds.csv')),
    ('SuppFig2_tolerance', PH[PH.grid == 'kw'][KW_COLS]),
    ('SuppFig3_objectives', r('reward_objectives.csv')),
    ('SuppFig4a_quadrature', r('quadrature_nll.csv')),
    ('SuppFig4b_w_profile', r('w_profile.csv')),
    ('SuppFig5_branches', r('branch_trajectories.csv')),
    ('SuppTable16_dense', r('dense_boundary.csv')),
]
with pd.ExcelWriter(OUT, engine='openpyxl') as xw:
    pd.DataFrame({'sheet': [s for s, _ in SHEETS], 'rows': [len(d) for _, d in SHEETS],
                  'note': ['Generated by analysis/make_source_data.py from data/processed; column definitions in README.md'] * len(SHEETS)}
                 ).to_excel(xw, sheet_name='README', index=False)
    for s, d in SHEETS:
        d.to_excel(xw, sheet_name=s[:31], index=False)
print('sheets', len(SHEETS))
